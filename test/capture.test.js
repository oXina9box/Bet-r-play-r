const assert = require('node:assert/strict');
const { createTracker } = require('../js/capture');
const game = require('../js/games/sicbo');
const tracker = createTracker();
const good = { round: '1881576828', raw: [6, 4, 6], result: { side: 'A', total: 16 }, resultText: 'BIG 16', confidence: 94, wager: { status: 'unknown' } };
const read = (value, time, entries = []) => tracker.read(value, { game, entries, now: time });
assert.equal(read(good, 0).status, 'pending');
assert.equal(read(good, 400).status, 'pending', 'samples must be separated');
const ready = read(good, 1600);
assert.equal(ready.status, 'ready');
assert.equal(ready.entry.screen.round, good.round);
assert.deepEqual(ready.entry.wager, { status: 'unknown' });
assert.equal(read(good, 3000, [ready.entry]).status, 'duplicate');
const next = { ...good, round: '1881576929' };
assert.equal(read(next, 4000).status, 'pending');
assert.equal(read(next, 5600).status, 'ready', 'identical rolls in different rounds are valid');
tracker.reset();
assert.equal(read({ ...good, raw: [1, 2, 3] }, 0).status, 'review', 'result and dice must agree');
assert.equal(read({ ...good, confidence: 20 }, 1).status, 'review');
assert.equal(read({ ...good, round: null }, 2).status, 'review');
assert.equal(read(null, 3).status, 'waiting', 'absent result banner cannot record stale dice');
tracker.reset();
read(good, 0);
read(null, 1600);
assert.equal(read(good, 3200).status, 'pending', 'missing result resets stability');
tracker.reset();
const actual = { ...good, wager: { status: 'observed', currency: 'GC', bets: [{ market: 'A', amount: 50 }] } };
read(actual, 0);
assert.equal(read(good, 1600).status, 'pending', 'changed wagers reset stability');
assert.equal(read(good, 3200).status, 'ready');
tracker.reset();
const triple = { ...good, raw: [4, 4, 4], result: { side: null, total: 12, triple: true }, resultText: 'TRIPLE 12' };
assert.equal(read(triple, 0).status, 'pending');
assert.equal(read(triple, 1600).status, 'ready', 'actual triples record without treating either side as a winner');
assert.equal(read({ ...good, raw: [4, 4, 4], result: { side: 'A', total: 12 } }, 2000).status, 'review');
assert.equal(read({ ...good, raw: [3, 4, 5], result: triple.result }, 3000).status, 'review');
const teenpatti = require('../js/games/teenpatti');
const hands = createTracker();
const hand = { ...good, raw: { c: ['Ah', 'Ad', 'As', 'Kh', 'Kd', 'Qh'] }, result: { side: 'A' }, resultText: 'PLAYER A' };
const readHand = (observation, now, entries = []) => hands.read(observation, { game: teenpatti, entries, now });
assert.equal(readHand(hand, 0).status, 'pending');
assert.equal(readHand(hand, 1600).status, 'ready');
assert.equal(readHand({ ...hand, result: { side: 'B' } }, 3000).status, 'review', 'OCR cards use grouped player hands');
assert.equal(teenpatti.outcome({ ...hand.raw, order: 'alternating' }).side, 'B', 'manual alternating hands keep their legacy interpretation');
const tied = { ...hand, raw: { c: ['Ah', 'Kc', '8d', 'As', 'Kd', '8c'] }, result: { side: null }, resultText: 'TIE' };
assert.equal(readHand(tied, 4000).status, 'pending');
assert.equal(readHand(tied, 5600).status, 'ready');
let evaluated = 0;
const strictGame = { ...teenpatti, outcome(raw) { evaluated++; return teenpatti.outcome(raw); } };
for (const raw of [{ w: 'A' }, { ...hand.raw, w: 'A' }, { c: ['As', 'As', 'As', '2h', '3d', '4c'] },
  { c: ['Zs', 'Zd', 'Zh', '2h', '3d', '4c'] }, { c: hand.raw.c.slice(0, 5) }, { ...hand.raw, order: 'alternating' }]) {
  assert.equal(hands.read({ ...hand, raw }, { game: strictGame, entries: [], now: 7000 }).status, 'review');
}
assert.equal(evaluated, 0, 'invalid screen hands must not reach winner evaluation');
const kickoff = require('../js/games/kickoff');
const rolls = createTracker();
const red = { ...good, raw: [6, 4], result: { side: 'A' }, resultText: 'RED' };
const readRoll = (observation, now, entries = []) => rolls.read(observation, { game: kickoff, entries, now });
assert.equal(readRoll(red, 0).status, 'pending');
assert.equal(readRoll(red, 1600).status, 'ready');
assert.equal(readRoll({ ...red, raw: [4, 6] }, 2000).status, 'review', 'red and blue dice order matters');
const blue = { ...red, raw: [2, 5], result: { side: 'B' }, resultText: 'BLUE' };
assert.equal(readRoll(blue, 3000).status, 'pending');
assert.equal(readRoll(blue, 4600).status, 'ready');
const draw = { ...red, raw: [3, 3], result: { side: null }, resultText: 'DRAW' };
assert.equal(readRoll(draw, 5000).status, 'pending');
assert.equal(readRoll(draw, 6600).status, 'ready');
let diceEvaluated = 0;
const strictDice = { ...kickoff, outcome(raw) { diceEvaluated++; return kickoff.outcome(raw); } };
for (const raw of [{ w: 'A' }, Object.assign([1, 6], { w: 'A' }), Array(2), [6, ,], [7, 4], [0, 2], [2.5, 1], [6], [6, 4, 1], ['6', 4], null]) {
  assert.equal(rolls.read({ ...red, raw }, { game: strictDice, entries: [], now: 7000 }).status, 'review');
}
assert.equal(diceEvaluated, 0, 'invalid screen dice must not reach winner evaluation');
const { trackWagers } = require('../js/capture');
const round = '1881590089';
const stake = amount => ({ status: 'observed', currency: 'GC', bets: [{ market: 'A', amount }] });
let wagerState = trackWagers({ stable: {}, candidate: null }, round, stake(50), 0);
assert.equal(wagerState.stable[round], undefined);
wagerState = trackWagers(wagerState, round, stake(50), 1600);
const priorWagers = wagerState;
assert.equal(wagerState.stable[round].wager.bets[0].amount, 50);
wagerState = trackWagers(wagerState, round, stake(100), 2000);
assert.equal(wagerState.stable[round], undefined, 'one changed stake invalidates older confirmed amount immediately');
assert.equal(priorWagers.stable[round].wager.bets[0].amount, 50, 'wager tracking is immutable');
wagerState = trackWagers(wagerState, undefined, { status: 'unknown' }, 3600);
assert.equal(wagerState.stable[round], undefined, 'settlement cannot revive an outdated wager');
wagerState = trackWagers(wagerState, round, stake(100), 4000);
wagerState = trackWagers(wagerState, round, stake(100), 5600);
assert.equal(wagerState.stable[round].wager.bets[0].amount, 100);
wagerState = trackWagers(wagerState, round, stake(0), 6000);
assert.equal(wagerState.stable[round], undefined, 'one visible cancellation invalidates an older stake');
wagerState = trackWagers(wagerState, round, stake(0), 7600);
assert.equal(wagerState.stable[round].wager.bets[0].amount, 0);
wagerState = trackWagers(wagerState, undefined, { status: 'unknown' }, 130000);
assert.equal(wagerState.stable[round], undefined, 'old wager evidence expires');
console.log('All capture tests passed');
